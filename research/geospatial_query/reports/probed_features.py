NOAA_DAV_IMAGERY = "noaa_dav_imagery_n"


def family(source: str, feature: str) -> str:
    return "spectral" if feature == NOAA_DAV_IMAGERY else SOURCES[source][0]


def main() -> None:
    assert {t for _, t, *_ in SOURCES.values()} <= OBSERVATION_TYPES
    aois = defaultdict(set)
    for lane in LANES:
        with (HERE / "probes" / lane / "poc" / "poc_values.csv").open() as fh:
            for r in csv.DictReader(fh):
                if r["value"].strip():
                    aois[r["source"], r["feature"]].add(r["aoi_id"])
    rows = []
    for (source, feature), hit in sorted(aois.items()):
        _, otype, url, licence, gap = SOURCES[source]
        rows.append({"family": family(source, feature), "feature": feature, "description": DESCRIPTIONS[feature],
                     "source": source, "observation_type": otype, "source_url": url, "licence": licence,
                     "gap": gap, "n_aois": len(hit)})
    with (HERE / "probed_features.csv").open("w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    print(f"{len(rows)} features from {len({r['source'] for r in rows})} sources")


if __name__ == "__main__":
    main()
