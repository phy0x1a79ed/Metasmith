"""Emit bibliography.bib + index.md from final_corpus.tsv + pdf_status.tsv."""
from __future__ import annotations
import csv, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FINAL = ROOT / "search" / "final_corpus.tsv"
STATUS = ROOT / "search" / "pdf_status.tsv"
BIB = ROOT / "bibliography.bib"
INDEX = ROOT / "index.md"
PDF_DIR_REL = "../.awm/data/literature/pdfs"


def cite_key(first_author: str, year: str, title: str) -> str:
    last = re.split(r"[\s,]+", first_author.strip())[0] or "anon"
    last = re.sub(r"[^A-Za-z0-9]+", "", last)
    word = (re.findall(r"[A-Za-z0-9]+", title.lower()) or ["x"])[0]
    return f"{last.lower()}{year}_{word}"


def bib_escape(s: str) -> str:
    # protect curly braces, ampersand, percent
    return s.replace("\\", r"\\").replace("&", r"\&").replace("%", r"\%").strip()


def bibtex_entry(row: dict, key: str) -> str:
    title = "{" + bib_escape(row["title"]) + "}"
    journal = bib_escape(row["journal"])
    author = bib_escape(row["first_author"]) + " and others"
    lines = [
        f"@article{{{key},",
        f"  author  = {{{author}}},",
        f"  title   = {title},",
        f"  journal = {{{journal}}},",
        f"  year    = {{{row['year']}}},",
        f"  doi     = {{{row['doi']}}},",
    ]
    if row.get("pmcid"):
        lines.append(f"  note    = {{{row['pmcid']}}},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    corpus = list(csv.DictReader(FINAL.open(), delimiter="\t"))
    status = {r["doi"]: r for r in csv.DictReader(STATUS.open(), delimiter="\t")}

    # bibliography.bib -- emit one @article per non-missing row (we still write
    # all 30 entries; tools like biber don't reject them)
    keys: dict[str, str] = {}
    with BIB.open("w") as f:
        f.write("% Auto-generated by scripts/build_bib.py from search/final_corpus.tsv\n")
        f.write("% Do not edit by hand -- rerun the script after curating selection_notes.md\n\n")
        for r in corpus:
            k = cite_key(r["first_author"], r["year"], r["title"])
            keys[r["doi"]] = k
            f.write(bibtex_entry(r, k) + "\n")

    # index.md -- table for humans
    band_order = ["review", "methodology", "biological", "bipartite"]
    band_titles = {
        "review": "Reviews (5)",
        "methodology": "Methodology / foundational BC (5)",
        "biological": "Metabolic-network topology + biological BC applications (15)",
        "bipartite": "Reaction-centric / bipartite / current-flow (5)",
    }

    lines: list[str] = []
    lines.append("# Betweenness-centrality literature corpus — index\n")
    lines.append("30 papers grounding the Phase-4 weighted current-flow betweenness work in prior art. Sorted by band; ★ = must-cite for the Phase-4 method.\n")
    lines.append(f"PDFs live under `{PDF_DIR_REL}/`. BibTeX in `bibliography.bib` (citation keys appear in the table).\n")

    for band in band_order:
        rows = [r for r in corpus if r["band"] == band]
        if not rows:
            continue
        lines.append(f"\n## {band_titles[band]}\n")
        lines.append("| ★ | Citation | Year | Journal | DOI | PDF | Why included |")
        lines.append("|---|----------|------|---------|-----|-----|--------------|")
        for r in sorted(rows, key=lambda x: (x["first_author"], x["year"])):
            must = "★" if r["must_cite"] == "yes" else ""
            doi = r["doi"]
            cite = f"`{keys[doi]}` &nbsp; {r['first_author']}"
            st = status.get(doi, {})
            if st.get("status") == "ok" and st.get("filename"):
                pdf_cell = f"[`{st['filename']}`]({PDF_DIR_REL}/{st['filename']})"
            else:
                pdf_cell = "_missing_"
            doi_cell = f"[{doi}](https://doi.org/{doi})"
            why = r["why_included"].replace("|", "\\|")
            lines.append(f"| {must} | {cite} | {r['year']} | {r['journal']} | {doi_cell} | {pdf_cell} | {why} |")

    n_total = len(corpus)
    n_pdf = sum(1 for r in corpus if (status.get(r["doi"]) or {}).get("status") == "ok")
    n_must = sum(1 for r in corpus if r["must_cite"] == "yes")
    lines.append(f"\n---\n**Summary:** {n_total} entries · {n_pdf} PDFs on disk · {n_must} must-cite ★ entries.\n")
    lines.append("\n**Missing PDFs** (paywalled, no OA copy found via PMC / Europe PMC / Unpaywall / bioRxiv / arxiv):\n")
    for doi, st in status.items():
        if st.get("status") != "ok":
            row = next((r for r in corpus if r["doi"] == doi), {})
            lines.append(f"- `{doi}` — {row.get('first_author','?')} ({row.get('year','?')}), {row.get('journal','?')}")

    INDEX.write_text("\n".join(lines) + "\n")
    print(f"wrote {BIB} ({n_total} entries) and {INDEX}")


if __name__ == "__main__":
    main()
