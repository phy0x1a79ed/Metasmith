"""Generate MS-DIAL 5 LC-MS lipidomics parameter files for POS and NEG batches.

MS-DIAL's console-app param format is a flat `key: value` text file (one option
per line, `#` for comments). Keys are matched case-insensitively by the parser
(see src/MSDIAL4/MsdialConsoleAppCore/Parser/ConfigParser.cs in the upstream
repo — same parser path is used by the v5 Linux build).

Lipid annotation is driven entirely by the `MSP file:` setting — we point at
the MS-DIAL TandemMassSpectralAtlas (LipidBlast) MSP that `install.sh`
downloaded into `lib/msdial/lipidblast/`. There is no in-param `lipid class
filter`: subclass selection happens by trimming the MSP (out of scope here —
we accept the full Atlas and filter downstream if needed).

Mass / RT / mobility tolerances are tuned for the timsTOF Pro DDA-PASEF
acquisition. The legacy MZmine batch (build_mzbatch.py) used MZmine-native
units; the values below are the MS-DIAL equivalents, kept as named constants
at the top of this file so they are auditable.

Run: mamba run -n lipidomics python research/fabfos/lipidomics/build_msdial_param.py
"""
from __future__ import annotations
from pathlib import Path

HERE = Path(__file__).parent
PROJECT = HERE.parents[2]
MSDIAL_LIB = PROJECT / "lib/msdial"

# --- tunable parameters ---------------------------------------------------
# Mass-axis tolerances (Da). timsTOF Pro ≈ 1-5 ppm typical; we use generous
# Da-domain values consistent with MS-DIAL's defaults for high-res Q-TOF.
MS1_TOL_CENTROID = 0.005
MS2_TOL_CENTROID = 0.01
MS1_TOL_IDENT = 0.01
MS2_TOL_IDENT = 0.05
MS1_TOL_ALIGN = 0.015

# RT range and tolerances (min). The acquisition is a ~30 min LC gradient;
# we keep a wide capture window and a small alignment tolerance.
RT_BEGIN = 0.0
RT_END = 35.0
RT_TOL_IDENT = 1.5
RT_TOL_ALIGN = 0.1

# Peak detection / deconvolution.
MIN_PEAK_HEIGHT = 100    # raw intensity threshold; msconvert mzML scales
MIN_PEAK_WIDTH = 4       # data points
MASS_SLICE_WIDTH = 0.1
SMOOTHING_LEVEL = 3

# Mass range — bacterial lipids span ~100 Da (FA) → ~1700 Da (CL species).
MZ_BEGIN = 100
MZ_END = 1700

# Lipid identification score cutoff (MS-DIAL scale 0-100). 70 is the default;
# we raise slightly to suppress chance matches against the 554k-spectra Atlas.
ID_SCORE_CUTOFF = 75

# Alignment knobs.
PEAK_COUNT_FILTER = 0.0           # keep all features; downstream filters
QC_AT_LEAST_FILTER = "True"
N_THREADS = 12                    # leave 4 cores headroom on a 16-core box

ADDUCTS_POS = ",".join([
    "[M+H]+", "[M+Na]+", "[M+K]+", "[M+NH4]+", "[M+H-H2O]+", "[2M+H]+",
])
ADDUCTS_NEG = ",".join([
    "[M-H]-", "[M+FA-H]-", "[M+Cl]-", "[M-H2O-H]-", "[2M-H]-", "[M-2H]2-",
])

MSP_POS = MSDIAL_LIB / "lipidblast" / "MSDIAL-TandemMassSpectralAtlas-VS69-Pos.msp"
MSP_NEG = MSDIAL_LIB / "lipidblast" / "MSDIAL-TandemMassSpectralAtlas-VS69-Neg.msp"


def build(polarity: str) -> str:
    is_pos = polarity == "pos"
    msp = MSP_POS if is_pos else MSP_NEG
    adducts = ADDUCTS_POS if is_pos else ADDUCTS_NEG
    ion_mode = "Positive" if is_pos else "Negative"

    return f"""# MS-DIAL 5 LC-MS lipidomics parameter file ({polarity.upper()})
# Generated by research/fabfos/lipidomics/build_msdial_param.py — do not edit by hand.

#Data type
MS1 data type: Centroid
MS2 data type: Centroid
Ion mode: {ion_mode}

#Data collection parameters
Retention time begin: {RT_BEGIN}
Retention time end: {RT_END}
Mass range begin: {MZ_BEGIN}
Mass range end: {MZ_END}

#Centroid parameters
MS1 tolerance for centroid: {MS1_TOL_CENTROID}
MS2 tolerance for centroid: {MS2_TOL_CENTROID}

#Peak detection parameters
Smoothing method: LinearWeightedMovingAverage
Smoothing level: {SMOOTHING_LEVEL}
Minimum peak width: {MIN_PEAK_WIDTH}
Minimum peak height: {MIN_PEAK_HEIGHT}
Mass slice width: {MASS_SLICE_WIDTH}

#Deconvolution parameters
Sigma window value: 0.5
MSMS abundance cut off: 10
Exclude after precursor ion: True
Keep isotope until: 0.5
Keep original precursor isotopes: False

#Adduct list
Adduct list: {adducts}

#MSP file and MS/MS identification setting
MSP file: {msp}

# Identification
Retention time tolerance for identification: {RT_TOL_IDENT}
Accurate ms1 tolerance for identification: {MS1_TOL_IDENT}
Accurate ms2 tolerance for identification: {MS2_TOL_IDENT}
Identification score cut off: {ID_SCORE_CUTOFF}
Use retention information for identification scoring: False
Use retention information for identification filtering: False

#Alignment parameters setting
Retention time tolerance for alignment: {RT_TOL_ALIGN}
MS1 tolerance for alignment: {MS1_TOL_ALIGN}
Retention time factor for alignment: 0.5
MS1 factor for alignment: 0.5
Peak count filter: {PEAK_COUNT_FILTER}
QC at least filter: {QC_AT_LEAST_FILTER}
Gap filling by compulsion: True

#Threads
Number of threads: {N_THREADS}
"""


def main() -> int:
    if not MSP_POS.exists() or not MSP_NEG.exists():
        print(f"WARN: MSP libraries not present at {MSDIAL_LIB}/lipidblast/.")
        print("      Run lib/msdial/install.sh to download them.")
    for pol in ("pos", "neg"):
        text = build(pol)
        out = HERE / f"pipeline_{pol}.msdial_param.txt"
        out.write_text(text)
        print(f"wrote {out.name}  ({len(text.splitlines())} lines, MSP={MSP_POS.name if pol=='pos' else MSP_NEG.name})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
