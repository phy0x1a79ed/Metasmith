#!/usr/bin/env python3
"""Emit the `isolate_rnaseq` mock library: its type file and one stub transform per TABLE row.

The stubs fill the gaps between the standard library's real transforms in the proposed
isolate RNA-seq pipeline for Beth's TCAG run DAV36692. Each stub's model is the proposal; its
body only touches its outputs. A row names, in `src`, the existing script it stands in for, or
`proposed` when nothing does yet.

    python research/beth_rnaseq/mocklib/generate.py
"""

from __future__ import annotations

import textwrap
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
TYPES_YML = HERE / "data_types" / "isolate_rnaseq.yml"
TRANSFORMS = HERE / "transforms" / "isolate_rnaseq"

FILE, DIR = "file", "dir"

# `_` is a matched property, so a distinct description keeps any two of these from standing in
# for one another.
TYPES: dict[str, tuple[str, dict]] = {
    "sample_sheet": (FILE, {"_": "one row per RNA library: sample, condition, replicate, batch", "ext": "tsv"}),
    "rrna_fraction": (FILE, {"_": "per-sample fraction of read pairs on rRNA and tRNA features", "ext": "tsv"}),
    "featurecounts_sweep": (DIR, {"_": "featureCounts run at each strandedness setting (-s 0, 1, 2)"}),
    "strandedness_report": (FILE, {"_": "assignment rate per strandedness setting and the setting chosen", "ext": "tsv"}),
    "raw_count_table": (FILE, {"_": "gene by library read-pair counts, columns named by library", "ext": "csv"}),
    "tpm_table": (FILE, {"_": "gene by library TPM, normalised on gene length", "ext": "tsv"}),
    "metal_gene_panel": (FILE, {"_": "fold change and TPM of the genes BacMet assigns to metal resistance", "ext": "svg"}),
    "qc_report": (FILE, {"_": "one RNA-seq QC report: trimming, mapping, rRNA, strandedness", "ext": "html"}),
}


@dataclass
class T:
    name: str
    src: str
    requires: list[tuple[str, str, list[str]]]
    products: list[tuple[str, str]]
    group_by: str
    note: str = ""
    cpus: int = 2
    memory_gb: int = 4
    hours: int = 1


def r(var, dtype, *parents):
    return var, dtype, list(parents)


EXP = r("exp", "transcriptomics::experiment")
BAMS = r("bam", "transcriptomics::bowtie2_bam", "exp")
GFF = r("gff", "sequences::gff", "exp")

TABLE: list[T] = [
    T("rrna_fraction", "proposed",
      [EXP, BAMS, r("nc", "annotation::bakta_gff", "exp")],
      [("out", "isolate_rnaseq::rrna_fraction")], group_by="exp",
      note="""Bacterial RNA-seq has no poly-A selection, so depletion efficiency decides the
      usable depth. Counted on Bakta's rRNA and tRNA features, since prodigal calls CDS only."""),
    T("featurecounts_strand_sweep", "nosco-phycocyanin transcriptomics/fir/count.sbatch",
      [EXP, BAMS, GFF], [("out", "isolate_rnaseq::featurecounts_sweep")], group_by="exp",
      cpus=8, memory_gb=16,
      note="featureCounts -p --countReadPairs -B -C -Q 10 -t CDS -g ID on the prodigal GFF, at -s 0, 1 and 2."),
    T("pick_strandedness", "proposed",
      [r("sweep", "isolate_rnaseq::featurecounts_sweep")],
      [("counts", "isolate_rnaseq::raw_count_table"), ("report", "isolate_rnaseq::strandedness_report")],
      group_by="sweep",
      note="Keeps the setting with the highest assignment rate."),
    T("apply_sample_sheet", "proposed",
      [EXP, r("raw", "isolate_rnaseq::raw_count_table", "exp"),
       r("sheet", "isolate_rnaseq::sample_sheet", "exp")],
      [("counts", "transcriptomics::gene_count_table")], group_by="exp",
      note="""deseq2 reads the condition from the column name, splitting off a trailing
      `-<replicate>`. TCAG names the libraries `epi300_cu1`, which carries no condition, so
      the columns are renamed `<condition>-<replicate>` from the sample sheet."""),
    T("tpm_within_genome", "nosco-phycocyanin transcriptomics tpm_within_organism.tsv",
      [r("raw", "isolate_rnaseq::raw_count_table"), r("gff", "sequences::gff")],
      [("tpm", "isolate_rnaseq::tpm_table")], group_by="raw"),
    T("metal_gene_panel", "proposed",
      [EXP, r("de", "transcriptomics::deseq2_results", "exp"),
       r("tpm", "isolate_rnaseq::tpm_table", "exp"),
       r("bacmet", "annotation::bacmet_diamond_results", "exp")],
      [("out", "isolate_rnaseq::metal_gene_panel")], group_by="exp",
      note="""The libraries are named `cu`; if that marks copper exposure, the first genes to
      read are the metal-resistance ones (cus, cop, cue in E. coli)."""),
    T("rnaseq_qc_report", "proposed",
      [EXP, r("trim", "sequences::fastp_json_report", "exp"),
       r("stats", "alignment::alignment_stats", "exp"),
       r("rrna", "isolate_rnaseq::rrna_fraction", "exp"),
       r("strand", "isolate_rnaseq::strandedness_report", "exp")],
      [("out", "isolate_rnaseq::qc_report")], group_by="exp"),
]

BANNER = "# generated by research/beth_rnaseq/mocklib/generate.py -- do not hand-edit\n"


def write_types() -> None:
    out = [BANNER, "types:\n"]
    for name, (_kind, props) in TYPES.items():
        out.append(f"  {name}:\n    properties:\n")
        for k, v in props.items():
            out.append(f"      {k}: {v!r}\n" if ":" in str(v) else f"      {k}: {v}\n")
    TYPES_YML.parent.mkdir(parents=True, exist_ok=True)
    TYPES_YML.write_text("".join(out))


def stub(row: T) -> str:
    head = [BANNER, f'"""{row.name} -- stands in for: {row.src}\n']
    if row.note:
        head.append("\n" + textwrap.fill(" ".join(row.note.split()), 90) + "\n")
    head.append('\nStub: the model is the proposal, the body only touches its outputs.\n"""\n\n')
    pad = max(len(v) for v, *_ in row.requires + row.products)
    body = ["from metasmith.python_api import *\n\n",
            "lib   = TransformInstanceLibrary.ResolveParentLibrary(__file__)\n",
            "model = Transform()\n"]
    for var, dtype, parents in row.requires:
        p = ", parents={%s}" % ", ".join(parents) if parents else ""
        body.append(f'{var:<{pad}} = model.AddRequirement(lib.GetType("{dtype}"){p})\n')
    for var, dtype in row.products:
        body.append(f'{var:<{pad}} = model.AddProduct(lib.GetType("{dtype}"))\n')
    dirs = {v for v, d in row.products if d.startswith("isolate_rnaseq::")
            and TYPES[d.split("::")[1]][0] == DIR}
    body += [
        "\n\ndef protocol(context: ExecutionContext):\n",
        "    made = {%s}\n" % ", ".join(f"{v}: context.Output({v})" for v, _ in row.products),
        "    for key, path in made.items():\n",
        "        make = 'mkdir -p' if key in _DIRECTORY_PRODUCTS else 'touch'\n",
        "        context.external_shell.Exec(f'{make} {path.external}')\n",
        "    return ExecutionResult(\n",
        "        manifest=[{k: v.local for k, v in made.items()}],\n",
        "        success=all(v.local.exists() for v in made.values()),\n",
        "    )\n\n\n",
        "_DIRECTORY_PRODUCTS = %s\n\n" % ("{%s}" % ", ".join(sorted(dirs)) if dirs else "set()"),
        "TransformInstance(\n",
        "    protocol=protocol,\n",
        "    model=model,\n",
        f"    group_by={row.group_by},\n",
        f"    resources=Resources(cpus={row.cpus}, memory=Size.GB({row.memory_gb}), duration=Duration(hours={row.hours})),\n",
        ")\n",
    ]
    return "".join(head + body)


def write_transforms() -> None:
    TRANSFORMS.mkdir(parents=True, exist_ok=True)
    for old in TRANSFORMS.glob("*.py"):
        if old.read_text().startswith(BANNER):
            old.unlink()
    for row in TABLE:
        (TRANSFORMS / f"{row.name}.py").write_text(stub(row))


if __name__ == "__main__":
    write_types()
    write_transforms()
    print(f"{len(TYPES)} types, {len(TABLE)} stubs")
